#!/usr/bin/env node

// Install the job-tracker plugin into DeepSeek Harness (dsh) from this checkout. See docs/dsh.md.
// Usage: node --no-warnings scripts/dsh-install.ts [--profile <name>]... [--uninstall]
//
// 1. Writes every command, skill and agent prompt as a dsh skill in $DSH_HOME/skills/job-tracker-<name>/.
//    dsh skill names cannot contain a colon, and dsh does not expand ${CLAUDE_PLUGIN_ROOT}, so the copies
//    are rewritten. Re-run this after editing the markdown.
// 2. Installs @deepseek-ai/dsh-hooks-claude-code into each profile (default: web and headless) and adds a
//    patch that mounts the tracker MCP server and hooks/dsh-hooks.json.

import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { basename, delimiter, dirname, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DSH_HOME = process.env.DSH_HOME || join(homedir(), '.dsh');
const SKILLS = join(DSH_HOME, 'skills');
const PREFIX = 'job-tracker-';
const MARKER = '.job-tracker-generated';
const BRIDGE = '@deepseek-ai/dsh-hooks-claude-code';
const BEGIN = '# >>> job-tracker';
const END = '# <<< job-tracker';
// Only the user types these; dsh's /name is their only entry point when model invocation is off.
const USER_ONLY = new Set(['approve', 'allow-consent']);

const args = process.argv.slice(2);
const uninstall = args.includes('--uninstall');
const profiles = args.flatMap((a, i) => (a === '--profile' && args[i + 1] ? [args[i + 1] as string] : []));
if (!profiles.length) profiles.push('web', 'headless');

function die(message: string): never {
  process.stderr.write(`${message}\n`);
  process.exit(1);
}

const [major = 0, minor = 0] = process.versions.node.split('.').map(Number);
if (major < 22 || (major === 22 && minor < 18)) die('node >= 22.18 required (node:sqlite, TypeScript type stripping)');
// Node refuses to strip types from files under node_modules, so `dsh plugin add` of this repo cannot work.
if (ROOT.split(sep).includes('node_modules')) die(`Run this from a git checkout, not from node_modules (${ROOT}).`);

interface Source {
  name: string;
  file: string;
  userInvocable: boolean;
  modelInvocable: boolean;
}

function sources(): Source[] {
  const commands = readdirSync(join(ROOT, 'commands')).filter((f) => f.endsWith('.md')).map((f) => basename(f, '.md'));
  const skills = readdirSync(join(ROOT, 'skills')).filter((d) => existsSync(join(ROOT, 'skills', d, 'SKILL.md')));
  const agents = readdirSync(join(ROOT, 'agents')).filter((f) => f.endsWith('.md')).map((f) => basename(f, '.md'));
  return [
    ...commands.map((c) => ({ name: `${PREFIX}${c}`, file: join(ROOT, 'commands', `${c}.md`), userInvocable: true, modelInvocable: !USER_ONLY.has(c) })),
    // One namespace, as on Hermes: on a clash the command keeps the name (users type it) and the skill gets "-guide".
    ...skills.map((s) => ({ name: `${PREFIX}${commands.includes(s) ? `${s}-guide` : s}`, file: join(ROOT, 'skills', s, 'SKILL.md'), userInvocable: true, modelInvocable: true })),
    ...agents.map((a) => ({ name: `${PREFIX}agent-${a}`, file: join(ROOT, 'agents', `${a}.md`), userInvocable: false, modelInvocable: true })),
  ];
}

function splitFrontmatter(text: string): { description: string; body: string } {
  const m = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) return { description: '', body: text };
  const line = (m[1] || '').split('\n').find((l) => l.startsWith('description:')) || '';
  return { description: line.slice('description:'.length).trim().replace(/^(["'])(.*)\1$/, '$2'), body: m[2] || '' };
}

function rewrite(text: string, root: string): string {
  return text.replaceAll(`\${CLAUDE_PLUGIN_ROOT}`, root).replaceAll('job-tracker:', PREFIX);
}

function renderSkill(src: Source, root: string): string {
  const { description, body } = splitFrontmatter(readFileSync(src.file, 'utf8'));
  const front = [
    '---',
    `name: ${src.name}`,
    // A JSON string is a valid YAML double-quoted scalar, so colons in the text cannot break the frontmatter.
    `description: ${JSON.stringify(rewrite(description, root))}`,
    ...(src.modelInvocable ? [] : ['disable-model-invocation: true']),
    ...(src.userInvocable ? [] : ['user-invocable: false']),
    '---',
  ];
  const files = basename(src.file) === 'SKILL.md' ? ` Files named here without a path (such as \`reference.md\`) are in \`${dirname(src.file)}\`.` : '';
  const note = `<!-- Generated by scripts/dsh-install.ts from ${src.file}. Edit that file and re-run the installer. -->\nPlugin root: \`${root}\`.${files}\n`;
  return `${front.join('\n')}\n\n${note}\n${rewrite(body, root).replace(/^\n+/, '')}`;
}

function removeGenerated(): void {
  if (!existsSync(SKILLS)) return;
  for (const d of readdirSync(SKILLS)) {
    // Only directories this script wrote: a user's own job-tracker-* skill has no marker.
    if (d.startsWith(PREFIX) && existsSync(join(SKILLS, d, MARKER))) rmSync(join(SKILLS, d), { recursive: true, force: true });
  }
}

function writeSkills(): number {
  const list = sources();
  for (const src of list) {
    const dir = join(SKILLS, src.name);
    if (existsSync(dir) && !existsSync(join(dir, MARKER))) die(`${dir} exists and was not written by this installer. Move it away and re-run.`);
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, 'SKILL.md'), renderSkill(src, ROOT));
    writeFileSync(join(dir, MARKER), `${src.file}\n`);
    // Skill resources (reference.md, guard.js) stay in the checkout; link them so relative names resolve.
    if (basename(src.file) === 'SKILL.md') {
      for (const f of readdirSync(dirname(src.file))) if (f !== 'SKILL.md') symlinkSync(join(dirname(src.file), f), join(dir, f));
    }
  }
  return list.length;
}

const yamlString = (s: string) => `'${s.replaceAll("'", "''")}'`;

function patchBlock(root: string, node: string): string {
  return [
    `${BEGIN} (written by ${join(root, 'scripts', 'dsh-install.ts')}; re-run it to update)`,
    '- insert:',
    '    - id: job-tracker-tracker',
    "      name: '@deepseek-ai/dsh-mcp-client'",
    '      config:',
    '        serverName: job_tracker',
    '        transport: stdio',
    `        command: ${yamlString(node)}`,
    `        args: [${yamlString('--no-warnings')}, ${yamlString(join(root, 'servers', 'tracker', 'src', 'index.ts'))}]`,
    '    - id: job-tracker-hooks',
    `      name: ${yamlString(BRIDGE)}`,
    '      config:',
    `        configPath: ${yamlString(join(root, 'hooks', 'dsh-hooks.json'))}`,
    `        pluginRoot: ${yamlString(root)}`,
    END,
  ].join('\n');
}

// Merge our block into a profile's patch list without touching the user's own entries. Returns null when the
// file is not a plain block sequence we can append to safely.
function mergePatch(existing: string, block: string | null): string | null {
  const start = existing.indexOf(BEGIN);
  const end = existing.indexOf(END);
  let rest = existing;
  if (start >= 0 && end > start) rest = existing.slice(0, start) + existing.slice(end + END.length).replace(/^\n/, '');
  rest = rest.replace(/\s+$/, '');
  if (!block) return rest ? `${rest}\n` : '';
  const content = rest.split('\n').filter((l) => l.trim() && !l.trim().startsWith('#'));
  if (content.some((l) => !/^(- |\s)/.test(l))) return null;
  return `${rest ? `${rest}\n` : ''}${block}\n`;
}

// Prefer the node on PATH (a version manager's shim survives Node upgrades) over this process's binary.
function nodePath(): string {
  for (const dir of (process.env.PATH || '').split(delimiter)) if (dir && existsSync(join(dir, 'node'))) return join(dir, 'node');
  return process.execPath;
}

function hasDsh(): boolean {
  return !spawnSync('dsh', ['--version'], { stdio: 'ignore' }).error;
}

function patchProfile(profile: string, block: string | null): void {
  const file = join(DSH_HOME, 'profiles', profile, 'cordis.patch.yml');
  const existing = existsSync(file) ? readFileSync(file, 'utf8') : '';
  const merged = mergePatch(existing, block);
  if (merged === null) {
    process.stdout.write(`${file} is not a plain patch list. Add this to it by hand:\n\n${block}\n\n`);
    return;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, merged);
}

removeGenerated();
if (uninstall) {
  for (const profile of profiles) patchProfile(profile, null);
  process.stdout.write(`Removed the job-tracker skills from ${SKILLS} and its entries from the ${profiles.join(', ')} profiles.\n`);
  process.exit(0);
}

const count = writeSkills();
const dsh = hasDsh();
for (const profile of profiles) {
  if (dsh) {
    const r = spawnSync('dsh', ['plugin', '--profile', profile, 'add', BRIDGE], { stdio: 'inherit' });
    if (r.status !== 0) die(`dsh plugin --profile ${profile} add ${BRIDGE} failed.`);
  }
  patchProfile(profile, patchBlock(ROOT, nodePath()));
}
process.stdout.write(`Wrote ${count} skills to ${SKILLS} and patched the ${profiles.join(', ')} profiles.\n`);
if (!dsh) process.stdout.write(`dsh is not on PATH. Install the hook bridge into each profile:\n${profiles.map((p) => `  dsh plugin --profile ${p} add ${BRIDGE}`).join('\n')}\n`);
process.stdout.write(`Restart dsh, then type /job-tracker-setup. Check the wiring with: dsh --profile ${profiles[0]} --dump-config\n`);
